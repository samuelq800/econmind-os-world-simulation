import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { createServer, type Server } from 'node:http';
import { once } from 'node:events';
import { beforeAll, describe, expect, it } from 'vitest';
import { inspectSocialSourceBindings } from '../../tools/office-connection/social-source-bindings.mjs';
import {
  createOfficialEdgeFetchHandler,
  OFFICIAL_EDGE_FUNCTION_PREFIX,
} from '../../apps/world-api/src/integration/official-edge-fetch-adapter.js';
import {
  loadOfficialSocialBindingsPublication,
  type OfficialSocialBindingsPublication,
} from '../../apps/world-api/src/integration/official-social-source-bindings-publication.js';
import { OFFICIAL_SOCIAL_BINDINGS_PATH } from '../../apps/world-api/src/integration/official-social-source-bindings-dto.js';

// Actual selected artifact, mapping and four raw datasets, no mock authority.
// Mutated-artifact rejection cases below are explicitly TEST_ONLY fixtures.
const hash = (bytes: Uint8Array) =>
  createHash('sha256').update(bytes).digest('hex');
const bytes = (value: unknown) =>
  new TextEncoder().encode(JSON.stringify(value, null, 2) + '\n');
const origin = 'https://source-ui.example';
const reader = {
  query: async () => {
    throw new Error('SOURCE_ROUTE_MUST_NOT_QUERY_SQL');
  },
};
const url = `https://official.example${OFFICIAL_EDGE_FUNCTION_PREFIX}${OFFICIAL_SOCIAL_BINDINGS_PATH}`;
let artifact: Awaited<ReturnType<typeof inspectSocialSourceBindings>>;
let input: Parameters<typeof loadOfficialSocialBindingsPublication>[0];
let publication: OfficialSocialBindingsPublication;
beforeAll(async () => {
  artifact = await inspectSocialSourceBindings();
  const artifactBytes = bytes(artifact);
  input = {
    artifactBytes,
    expectedArtifactSHA256: hash(artifactBytes),
    mappingBytes: await readFile(
      new URL(
        '../../docs/reports/world-connection/C_OFFICIAL_WORLD_OPENING_MAPPING.json',
        import.meta.url,
      ),
    ),
    datasetBytes: Object.fromEntries(
      await Promise.all(
        ['employment', 'population-services', 'regions', 'facilities'].map(
          async (name) => [
            name,
            await readFile(
              new URL(
                `../../artifacts/world-balanced-candidate-v1/data/${name}.json`,
                import.meta.url,
              ),
            ),
          ],
        ),
      ),
    ),
  };
  publication = await loadOfficialSocialBindingsPublication(input);
});
const handler = () =>
  createOfficialEdgeFetchHandler({
    reader,
    allowedOrigins: [origin],
    socialBindings: publication,
  });
async function body(path = '') {
  const response = await handler()(new Request(url + path));
  return { response, value: await response.json() };
}
async function mutated(change: (value: typeof artifact) => void) {
  const clone = structuredClone(artifact);
  change(clone);
  const artifactBytes = bytes(clone);
  return loadOfficialSocialBindingsPublication({
    ...input,
    artifactBytes,
    expectedArtifactSHA256: hash(artifactBytes),
  });
}

describe('actual selected Social binding publication — derived evidence, not live World', () => {
  it('loads all 1066 unresolved rows and pins independently hashed generated bytes and source authorities', () => {
    expect(publication.rows).toHaveLength(1066);
    expect(publication.metadata).toMatchObject({
      dataNature: 'SELECTED_SOURCE_DERIVED_NOT_LIVE_WORLD',
      bindingFingerprint: `sha256:${hash(input.artifactBytes)}`,
      checksumsSHA256: artifact.source.checksumsSHA256,
      mappingSHA256: artifact.source.mapping.sha256,
      ownerRuleSHA256: artifact.source.ownerOriginal.sha256,
      originalCompositeGaps: 1066,
      fullyClosedCompositeGaps: 0,
      unresolvedCompositeGaps: 1066,
      sourceAdmitted: false,
      liveWorldState: false,
      operationalService: false,
      deployed: false,
    });
    expect(publication.metadata.bindingFingerprint).not.toBe(
      `sha256:${publication.metadata.checksumsSHA256}`,
    );
    expect(
      Object.isFrozen(publication.rows[0]!.subfields[0]!.sourceReferences),
    ).toBe(true);
  });

  it('exposes only the public subset and distinguishes exact leaf, derivation and inspected parent references', () => {
    const encoded = JSON.stringify(publication);
    for (const privateKey of [
      'privateCustody',
      'OWNER_NON_HOST_DECISIONS.original.md',
      'OWNER_NON_HOST_DECISION_RECEIPT.json',
      '"originalGap":',
      'source-private-authorization',
    ])
      expect(encoded).not.toContain(privateKey);
    const required = publication.rows[0]!.subfields.find(
      (field) => field.field === 'requiredCount',
    )!;
    expect(
      required.sourceReferences.every(
        (ref) => ref.relation === 'EXACT_SOURCE_VALUE',
      ),
    ).toBe(true);
    const missing = publication.rows[0]!.subfields.find(
      (field) => field.field === 'wageAmount',
    )!;
    expect(missing).toMatchObject({
      status: 'MISSING',
      value: null,
      absenceClaimScope: 'INSPECTED_SOURCE_PARENTS_ONLY_NOT_GLOBAL_ABSENCE',
    });
    expect(
      missing.sourceReferences.every(
        (ref) => ref.relation === 'CHECKED_PARENT_RECORD',
      ),
    ).toBe(true);
    const role = publication.rows[0]!.subfields.find(
      (field) => field.field === 'employerRole',
    )!;
    expect(role.sourceReferences[0]).toMatchObject({
      namespace: 'OWNER_RULE',
      path: 'D04_OWNER_RULE',
      relation: 'DERIVATION_INPUT',
    });
  });

  it('uses exact mapping joins and source grain, retaining country totals and regional school/hospital/housing aggregates', async () => {
    const mapping = JSON.parse(
      new TextDecoder().decode(input.mappingBytes),
    ).mappings;
    for (const row of publication.rows) {
      expect(
        mapping.countries.find(
          (item: { coreCountryId: string }) =>
            item.coreCountryId === row.countryId,
        ).sourceCountryId,
      ).toBe(row.sourceCountryId);
      if (row.locationId !== null)
        expect(
          mapping.regions.find(
            (item: { normalizedRegionId: string }) =>
              item.normalizedRegionId === row.locationId,
          ).sourceRegionId,
        ).toBe(row.sourceRegionId);
      if (row.economicEntityId !== null)
        expect(
          mapping.entityProposals.find(
            (item: { proposedCoreLegalEntityId: string }) =>
              item.proposedCoreLegalEntityId === row.economicEntityId,
          ).sourceEntityId,
        ).toBe(row.sourceEconomicEntityId);
    }
    const { response, value } = await body(
      '?countryId=visual-territory-01&limit=50',
    );
    expect(response.status).toBe(200);
    expect(
      value.rows.every(
        (row: { sourceCountryId: string; countryId: string }) =>
          row.sourceCountryId === 'visual-territory-01' &&
          row.countryId === 'COUNTRY_01',
      ),
    ).toBe(true);
    const totals = publication.rows.filter(
      (row) => row.serviceKind === 'COUNTRY_AGGREGATE',
    );
    expect(totals.length).toBe(700);
    expect(totals.every((row) => row.locationId === null)).toBe(true);
    const employment = totals.filter(
      (row) => row.field === 'employmentByRegionAndSkill',
    );
    expect(employment).toHaveLength(70);
    expect(employment.every((row) => row.economicEntityId === null)).toBe(true);
    expect(publication.rows[0]).toMatchObject({
      sourceProjectId: 'PROJECT-31',
      serviceGrain: 'REGIONAL_EDUCATION_AGGREGATE',
    });
    expect(new Set(publication.rows.map((row) => row.serviceKind))).toEqual(
      new Set([
        'COUNTRY_AGGREGATE',
        'BASIC_EDUCATION',
        'HOSPITAL',
        'ORDINARY_HOUSING',
      ]),
    );
  });

  it('paginates the actual artifact within byte budget without dropping, duplicating or closing gaps', async () => {
    const read = handler();
    const keys: string[] = [];
    let offset = 0;
    do {
      const response = await read(
        new Request(
          `${url}?limit=50&offset=${offset}&bindingFingerprint=${publication.metadata.bindingFingerprint}`,
        ),
      );
      expect(response.status).toBe(200);
      const text = await response.text();
      expect(new TextEncoder().encode(text).byteLength).toBeLessThanOrEqual(
        256000,
      );
      const page = JSON.parse(text);
      expect(page.page.returned).toBeGreaterThan(0);
      expect(page.page.total).toBe(1066);
      expect(page.fullyClosedCompositeGaps).toBe(0);
      keys.push(...page.rows.map((row: { gapKey: string }) => row.gapKey));
      if (page.page.nextOffset === null) break;
      expect(page.page.nextOffset).toBeGreaterThan(offset);
      offset = page.page.nextOffset;
    } while (offset < 1066);
    expect(keys).toEqual(publication.rows.map((row) => row.gapKey));
    expect(new Set(keys).size).toBe(1066);
  });

  it('returns a genuine empty final page separately from unavailable publication', async () => {
    const { response, value } = await body(
      `?offset=1066&bindingFingerprint=${publication.metadata.bindingFingerprint}`,
    );
    expect(response.status).toBe(200);
    expect(value).toMatchObject({
      ok: true,
      status: 'EMPTY',
      rows: [],
      page: { returned: 0, total: 1066, nextOffset: null },
    });
    const closed = createOfficialEdgeFetchHandler({
      reader,
      allowedOrigins: [origin],
    });
    const unavailable = await closed(new Request(url));
    expect(unavailable.status).toBe(503);
    expect(await unavailable.json()).toEqual({
      ok: false,
      error: { code: 'SOURCE_BINDING_UNAVAILABLE' },
    });
  });

  it('requires a generated binding version for continuation and rejects stale versions without rows', async () => {
    expect((await body('?offset=1')).response.status).toBe(400);
    const { response, value } = await body(
      `?offset=1&bindingFingerprint=sha256:${'0'.repeat(64)}`,
    );
    expect(response.status).toBe(409);
    expect(value).toEqual({
      ok: false,
      error: { code: 'STALE_BINDING_VERSION' },
    });
  });

  it('changes binding version when generated bytes change even with the same raw version', async () => {
    const artifactBytes = new TextEncoder().encode(
      new TextDecoder().decode(input.artifactBytes) + '\n',
    );
    const next = await loadOfficialSocialBindingsPublication({
      ...input,
      artifactBytes,
      expectedArtifactSHA256: hash(artifactBytes),
    });
    expect(next.metadata.checksumsSHA256).toBe(
      publication.metadata.checksumsSHA256,
    );
    expect(next.metadata.bindingFingerprint).not.toBe(
      publication.metadata.bindingFingerprint,
    );
  });

  it('serves HEAD/CORS/OPTIONS with no-store and no credential capability', async () => {
    const read = handler();
    const get = await read(new Request(url, { headers: { origin } }));
    const head = await read(
      new Request(url, { method: 'HEAD', headers: { origin } }),
    );
    expect(head.status).toBe(200);
    expect(await head.text()).toBe('');
    expect(head.headers.get('content-length')).toBe(
      get.headers.get('content-length'),
    );
    expect(head.headers.get('cache-control')).toBe('no-store');
    expect(head.headers.get('access-control-allow-origin')).toBe(origin);
    expect(head.headers.get('access-control-allow-credentials')).toBeNull();
    const preflight = await read(
      new Request(url, {
        method: 'OPTIONS',
        headers: { origin, 'access-control-request-method': 'HEAD' },
      }),
    );
    expect(preflight.status).toBe(204);
    const denied = await read(
      new Request(url, {
        method: 'OPTIONS',
        headers: {
          origin: 'https://foreign.example',
          'access-control-request-method': 'GET',
        },
      }),
    );
    expect(denied.status).toBe(403);
    expect(denied.headers.get('access-control-allow-origin')).toBeNull();
  });

  it.each([
    '?countryId=COUNTRY_01',
    '?countryId=visual-territory-71',
    '?countryId=visual-territory-01&countryId=visual-territory-02',
    '?limit=51',
    '?offset=-1',
    '?offset=01',
    '?path=/tmp/private',
    '?bindingFingerprint=bad',
  ])('rejects unsupported parameters %s', async (query) => {
    expect((await body(query)).response.status).toBe(400);
  });

  it('keeps fixed routing closed to methods, suffixes and unbranded objects', async () => {
    expect((await handler()(new Request(url, { method: 'POST' }))).status).toBe(
      405,
    );
    expect((await handler()(new Request(url + '/foreign'))).status).toBe(404);
    expect(() =>
      createOfficialEdgeFetchHandler({
        reader,
        allowedOrigins: [],
        socialBindings: { ...publication },
      }),
    ).toThrow('SOURCE_INVALID');
  });

  it('rejects TEST_ONLY byte/hash, source/mapping/version, ID, provenance and closure substitutions', async () => {
    await expect(
      loadOfficialSocialBindingsPublication({
        ...input,
        expectedArtifactSHA256: '0'.repeat(64),
      }),
    ).rejects.toThrow('SOURCE_INVALID');
    await expect(
      loadOfficialSocialBindingsPublication({
        ...input,
        mappingBytes: new TextEncoder().encode('{}'),
      }),
    ).rejects.toThrow('SOURCE_INVALID');
    const badData = {
      ...input.datasetBytes,
      employment: new TextEncoder().encode('[]'),
    };
    await expect(
      loadOfficialSocialBindingsPublication({
        ...input,
        datasetBytes: badData,
      }),
    ).rejects.toThrow('SOURCE_INVALID');
    for (const change of [
      (value: typeof artifact) => {
        value.source.checksumsSHA256 = '0'.repeat(64);
      },
      (value: typeof artifact) => {
        value.source.ownerOriginal.sha256 = '0'.repeat(64);
      },
      (value: typeof artifact) => {
        value.rows[0]!.sourceCountryId = 'visual-territory-02';
      },
      (value: typeof artifact) => {
        value.rows[0]!.sourceRegionId = 'visual-territory-02-E1';
      },
      (value: typeof artifact) => {
        value.rows[0]!.fullyClosed = true;
      },
      (value: typeof artifact) => {
        value.summary.fullyClosedCompositeGaps = 1;
      },
      (value: typeof artifact) => {
        value.rows[0]!.subfields[0]!.sourceReferences[0]!.pointer = '/0';
      },
      (value: typeof artifact) => {
        value.rows[0]!.subfields[0]!.sourceReferences[0]!.sha256 = '0'.repeat(
          64,
        );
      },
    ])
      await expect(mutated(change)).rejects.toThrow('SOURCE_INVALID');
  });

  it('reads actual generated evidence through an owned loopback HTTP server and always cleans it up', async () => {
    const read = handler();
    let server: Server | undefined;
    try {
      server = createServer((request, response) => {
        void (async () => {
          const result = await read(
            new Request(
              `http://127.0.0.1${OFFICIAL_EDGE_FUNCTION_PREFIX}${request.url}`,
              { method: request.method ?? 'GET', headers: { origin } },
            ),
          );
          response.writeHead(result.status, Object.fromEntries(result.headers));
          response.end(new Uint8Array(await result.arrayBuffer()));
        })().catch(() => {
          response.writeHead(500);
          response.end();
        });
      });
      server.listen(0, '127.0.0.1');
      await once(server, 'listening');
      const address = server.address();
      if (address === null || typeof address === 'string')
        throw new Error('LOOPBACK_PORT_UNAVAILABLE');
      const response = await fetch(
        `http://127.0.0.1:${address.port}${OFFICIAL_SOCIAL_BINDINGS_PATH}?countryId=visual-territory-01&limit=1`,
      );
      expect(response.status).toBe(200);
      expect(response.headers.get('access-control-allow-origin')).toBe(origin);
      const page = await response.json();
      expect(page.bindingFingerprint).toBe(
        publication.metadata.bindingFingerprint,
      );
      expect(page.rows[0].gapKey).toBe(publication.rows[0]!.gapKey);
      expect(
        page.rows[0].subfields.find(
          (field: { field: string }) => field.field === 'requiredCount',
        ).value,
      ).toBe('771012');
    } finally {
      if (server?.listening)
        await new Promise<void>((resolve, reject) => {
          server!.close((error) => (error ? reject(error) : resolve()));
          server!.closeAllConnections();
        });
    }
    expect(server?.listening).toBe(false);
  });
});
