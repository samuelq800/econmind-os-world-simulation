import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = path.join(
  root,
  'database/types/world-v2-read-model.schema.json',
);
const outputPath = path.join(
  root,
  'apps/world-api/src/integration/generated/world-v2-read-model.ts',
);
const schema = JSON.parse(await readFile(inputPath, 'utf8'));
const typeMap = {
  bigint: 'string',
  boolean: 'boolean',
  jsonb: 'JsonValue',
  text: 'string',
  timestamptz: 'string',
  uuid: 'string',
};

function pascal(value) {
  return value
    .split('_')
    .map((part) => `${part[0]?.toUpperCase() ?? ''}${part.slice(1)}`)
    .join('');
}

function typescriptType(specification) {
  const nullable = specification.endsWith('|null');
  const base = nullable ? specification.slice(0, -5) : specification;
  const mapped = typeMap[base];
  if (!mapped) throw new Error(`Unsupported database type: ${base}`);
  return nullable ? `${mapped} | null` : mapped;
}

const tableEntries = Object.entries(schema.tables);
const rows = tableEntries
  .map(([tableName, table]) => {
    const fields = Object.entries(table.columns)
      .map(
        ([columnName, specification]) =>
          `  readonly ${columnName}: ${typescriptType(specification)};`,
      )
      .join('\n');
    return `export interface ${pascal(tableName)}Row {\n${fields}\n}`;
  })
  .join('\n\n');
const columns = tableEntries
  .map(
    ([tableName, table]) =>
      `  ${tableName}: Object.freeze(${JSON.stringify(Object.keys(table.columns))}),`,
  )
  .join('\n');
const databaseTables = tableEntries
  .map(
    ([tableName]) =>
      `      readonly ${tableName}: {\n        readonly Row: ${pascal(tableName)}Row;\n        readonly Insert: never;\n        readonly Update: never;\n      };`,
  )
  .join('\n');

const output = await format(
  `// Generated by scripts/generate-world-v2-read-types.mjs. Do not edit.\n// Source: database/types/world-v2-read-model.schema.json\n\nimport type { JsonValue } from '../contracts.js';\n\nexport const WORLD_V2_READ_MODEL_TYPE_VERSION = ${JSON.stringify(schema.schemaVersion)} as const;\nexport const WORLD_V2_READ_MODEL_SOURCE_MIGRATION = ${JSON.stringify(schema.sourceMigration)} as const;\n\nexport const WORLD_V2_READ_TABLE_COLUMNS = Object.freeze({\n${columns}\n});\n\n${rows}\n\nexport interface WorldV2ReadDatabase {\n  readonly world_v2: {\n    readonly Tables: {\n${databaseTables}\n    };\n    readonly Views: Record<string, never>;\n    readonly Functions: Record<string, never>;\n  };\n}\n`,
  { parser: 'typescript', singleQuote: true },
);

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== output) {
    console.error('WORLD_V2_READ_TYPES_OUT_OF_DATE');
    process.exitCode = 1;
  } else {
    console.log('WORLD_V2_READ_TYPES_CURRENT');
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, 'utf8');
  console.log('WORLD_V2_READ_TYPES_GENERATED');
}
